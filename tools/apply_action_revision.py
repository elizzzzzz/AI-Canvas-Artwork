def main():
    patch_scripts()
    workflow=json.loads((ROOT/'production/workflow-v1.json').read_text())
    for shot in workflow['shots']:
        info=ACTION.get(shot['key'])
        shot['action_scene']=bool(info)
        shot['action_type']=info['type'] if info else '任务观察/信息核验'
        shot['action_seconds']=shot['duration'] if info else 0
        shot['action_intensity']='high' if info else 'low'
        if info:
            shot['action'] = shot.get('action','') + ' 动作强化：' + ' '.join(info['beats'])
            for idx,clip in enumerate(shot['clips']):
                clip['action_scene']=True;clip['action_type']=info['type'];clip['action_phase']=idx+1
                beat=info['beats'][idx % len(info['beats'])]
                clip['prompt']=re.sub(r'ACTION_BEATS:[^\n]*', 'ACTION_BEATS: '+beat, clip['prompt'], count=1)
                marker='ACTION_CAMERA_SAFETY: 全程第一人称；动作主体保持在主人公眼高或手边可见范围；不得反打主人公，不得变成第三人称全知机位。'
                if 'ACTION_CAMERA_SAFETY:' not in clip['prompt']:
                    clip['prompt']=clip['prompt'].replace('CONTINUITY_LOCKS:',marker+'\nCONTINUITY_LOCKS:',1)
        else:
            for clip in shot['clips']:
                clip['action_scene']=False;clip['action_type']='任务观察/信息核验';clip['action_phase']=0
    action_manifest={'version':1,'status':'action_revision_v1_pending_3d_motion_review','minimum_ratio':0.5,
      'rule':'动作时长按明确战争、冲突、追逐、拦截、失控抢救或高压调度镜头的全部时长计；不以数量替代时长。',
      'episodes':[],'first_person_rule':'所有动作仍为主人公第一人称；敌对者、追兵、信使和支援人员只在主人公可见范围内出现。'}
    for ep in (1,2,3):
        shots=[s for s in workflow['shots'] if s['episode']==ep]
        selected=[s for s in shots if s['action_scene']]
        total=sum(s['duration'] for s in shots);action=sum(s['action_seconds'] for s in selected)
        action_manifest['episodes'].append({'episode':ep,'total_seconds':total,'action_seconds':action,'ratio':round(action/total,4),
          'status':'passes_target_pending_3d_motion_review','action_shots':[{'key':s['key'],'title':s['title'],'seconds':s['action_seconds'],'type':s['action_type']} for s in selected]})
    workflow['action_coverage']={'version':1,'status':'action_revision_v1_pending_3d_motion_review','manifest':'production/action-coverage-v1.json'}
    (ROOT/'production/action-coverage-v1.json').write_text(json.dumps(action_manifest,ensure_ascii=False,indent=2)+'\n')
    (ROOT/'production/workflow-v1.json').write_text(json.dumps(workflow,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps({'episodes':[(e['episode'],e['action_seconds'],e['total_seconds'],e['ratio']) for e in action_manifest['episodes']]},ensure_ascii=False))

if __name__=='__main__':main()
